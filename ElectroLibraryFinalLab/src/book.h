// Структура Book — «обёртка» для передачи данных о книге между слоями приложения.
// Не является QObject; используется как простой контейнер (DTO).

#pragma once
#include <QString>

struct Book {
    int     id = -1;          // Идентификатор в БД (-1 = новая, ещё не сохранённая)
    QString title;            // Название книги (обязательное поле)
    QString author;           // Автор книги (обязательное поле)
    int     year = 0;         // Год издания
    QString isbn;             // ISBN (10 или 13 цифр, может быть пустым)
    QString genre;            // Жанр (свободный текст или из предустановленного списка)
    QString status = "to_read"; // Статус: to_read / reading / done
    int     rating = 0;       // Рейтинг от 0 до 5
    int     pages = 0;        // Количество страниц
    QString notes;            // Заметки пользователя
};
